<script>
    $(document).ready(function(){
        var scale = 1;
        var isDragging = false;
        var startX, startY, translateX = 0, translateY = 0;

        function updateTransform() {
            $('#image').css('transform', 'scale(' + scale + ') translate(' + translateX + 'px, ' + translateY + 'px)');
        }

        function handleZoomIn() {
            scale += 0.1;
            updateTransform();
        }

        function handleZoomOut() {
            if (scale > 0.1) {
                scale -= 0.1;
                updateTransform();
            }
        }

        function handleReset() {
            scale = 1;
            translateX = 0;
            translateY = 0;
            updateTransform();
        }

        $('#zoom-in').on('click touchstart', function(e) {
            e.preventDefault();
            handleZoomIn();
        });

        $('#zoom-out').on('click touchstart', function(e) {
            e.preventDefault();
            handleZoomOut();
        });

        $('#reset').on('click touchstart', function(e) {
            e.preventDefault();
            handleReset();
        });

        function startDragging(e) {
            isDragging = true;
            var clientX = e.type === 'touchstart' ? e.touches[0].clientX : e.pageX;
            var clientY = e.type === 'touchstart' ? e.touches[0].clientY : e.pageY;
            startX = clientX - translateX;
            startY = clientY - translateY;
            $('.img-container').css('cursor', 'grabbing');
            e.preventDefault();
        }

        function stopDragging() {
            isDragging = false;
            $('.img-container').css('cursor', 'grab');
        }

        function dragImage(e) {
            if (isDragging) {
                var clientX = e.type === 'touchmove' ? e.touches[0].clientX : e.pageX;
                var clientY = e.type === 'touchmove' ? e.touches[0].clientY : e.pageY;
                translateX = clientX - startX;
                translateY = clientY - startY;
                updateTransform();
            }
        }

        $('.img-container').on('mousedown touchstart', startDragging);
        $(document).on('mouseup touchend', stopDragging);
        $(document).on('mousemove touchmove', dragImage);

        // Prevent default image dragging behavior
        $('#image').on('dragstart', function(e) {
            e.preventDefault();
        });
    });
</script>

